/**
 * Pluggable Bible data sources.
 *
 * Every version the operator can pick is a `BibleSource`. The UI only talks
 * to the registry below, so adding a version means registering another
 * source — no UI changes. Today there is one kind (local public-domain JSON
 * files); later steps add API.Bible and user-imported versions.
 */
import type { BookId } from "./books";
import type { BibleFile, VersionInfo, Verse } from "./types";

export interface BibleSource {
  info: VersionInfo;
  /**
   * Verse texts of one chapter, index 0 = verse 1. A verse this version
   * doesn't include is "". Returns null if the chapter isn't available.
   */
  getChapter(book: BookId, chapter: number): Promise<string[] | null>;
}

/** A version stored as /bibles/<id>.json (generated by scripts/build-bibles.mjs). */
export class LocalJsonSource implements BibleSource {
  private file: Promise<BibleFile> | null = null;

  constructor(public info: VersionInfo) {}

  /** Downloads the whole version once and keeps it in memory (~4 MB each). */
  load(): Promise<BibleFile> {
    if (!this.file) {
      this.file = fetch(`/bibles/${encodeURIComponent(this.info.id)}.json`).then((res) => {
        if (!res.ok) throw new Error(`Could not load ${this.info.label} (HTTP ${res.status})`);
        return res.json() as Promise<BibleFile>;
      });
      this.file.catch(() => (this.file = null)); // allow retry after a failure
    }
    return this.file;
  }

  async getChapter(book: BookId, chapter: number): Promise<string[] | null> {
    const file = await this.load();
    return file.books[book]?.[chapter - 1] ?? null;
  }
}

// ---------------------------------------------------------------------------
// Registry
// ---------------------------------------------------------------------------

export const DEFAULT_VERSION = "KJV";

const sources = new Map<string, BibleSource>();
let ready: Promise<VersionInfo[]> | null = null;

/** Adds (or replaces) a version. Future sources (API.Bible, imports) call this. */
export function registerSource(source: BibleSource) {
  sources.set(source.info.id, source);
}

export function getSource(id: string): BibleSource | undefined {
  return sources.get(id);
}

export function listVersions(): VersionInfo[] {
  return [...sources.values()].map((s) => s.info);
}

/**
 * Registers the bundled offline versions listed in /bibles/manifest.json.
 * Safe to call many times; only does the work once.
 */
export function initSources(): Promise<VersionInfo[]> {
  if (!ready) {
    ready = fetch("/bibles/manifest.json")
      .then((res) => {
        if (!res.ok) throw new Error(`Could not load the Bible list (HTTP ${res.status})`);
        return res.json() as Promise<VersionInfo[]>;
      })
      .then((list) => {
        for (const info of list) if (!sources.has(info.id)) registerSource(new LocalJsonSource(info));
        // Warm up the default version first, then the rest in the background
        // so switching versions during the service is instant.
        const def = sources.get(DEFAULT_VERSION);
        const warm = (s: BibleSource | undefined) => (s instanceof LocalJsonSource ? s.load().catch(() => {}) : Promise.resolve());
        warm(def).then(() => {
          for (const s of sources.values()) if (s !== def) warm(s);
        });
        return listVersions();
      });
    ready.catch(() => (ready = null));
  }
  return ready;
}

/** Convenience: one verse as a normalised record, or null if unavailable. */
export async function getVerse(version: string, book: BookId, chapter: number, verse: number): Promise<Verse | null> {
  const chapterTexts = await getSource(version)?.getChapter(book, chapter);
  if (!chapterTexts) return null;
  return { version, book, chapter, verse, text: chapterTexts[verse - 1] ?? "" };
}
